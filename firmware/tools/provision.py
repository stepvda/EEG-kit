#!/usr/bin/env python3
"""
provision.py -- end-of-line provisioning for the EEG field kit (RFQ F-18).

This is the script the manufacturer runs on every unit, after flashing and after the
functional test has produced its calibration numbers.  It is deliberately boring: it does
one thing per step, prints what it did, refuses to continue if a step fails, and writes a
signed-off record that travels with the unit.

    python3 provision.py --port /dev/ttyACM0 --serial TIOV-B-0007 \
                         --calibration cal_TIOV-B-0007.json \
                         --out records/TIOV-B-0007.json \
                         --write-config --lock

WHAT THIS SCRIPT DOES AND DOES NOT DO
  It does:      write the ATECC608B configuration zone from the template, lock it, generate the
                P-256 key pair inside the element, read back the public key and the chip serial,
                write the USB VID/PID, hardware revision and unit serial, write the calibration
                constants measured at test, verify the lock, and emit the per-unit record.
  It does NOT:  hold, see or transmit the firmware signing key.  The manufacturer flashes an
                image that the programme has already signed (RFQ F-19).  The private device
                key is generated inside the secure element and cannot be read out by anyone,
                including us.

THE TWO IRREVERSIBLE STEPS ARE BOTH BEHIND A FLAG
  ASM-EEG-007 section 6.1 promises that "the script requires an explicit `--lock` and prints
  the scanned board serial back for confirmation", and FW-EEG-001 section 7.2 promises that it
  "rejects any argument that does not match the registered format".  Neither existed: there was
  no `--lock` argument at all -- an operator typing the documented command line got an argparse
  error -- the configuration zone was locked unconditionally at step 8, and `--serial
  NOT-A-SERIAL` was accepted and written into NVS, the ATECC data zone and the record.  Both
  promises are kept here: `--serial` is checked against PKG-EEG-015 section 5, and the lock
  needs `--lock` plus the serial typed or passed back.

THE STEP ORDER IS NOT FW-EEG-001 SECTION 7.3's, AND CANNOT BE
  That table puts GenKey at step 3 and the configuration-zone lock at step 8.  On a
  factory-fresh part the sequence cannot work: the part will not generate a key into a slot
  whose configuration has not been written and locked, so step 3 fails -- and step 8 would then
  lock the default Microchip configuration, permanently scrapping the breakout without ever
  creating the device identity.  The write and the lock therefore run as steps 2b and 2c,
  before GenKey, and old step 8 becomes the read-back that confirms the lock took, which is
  what TST-EEG-004 T6's acceptance limit actually asks for.  Old step 9 read the provisioning
  state with that same 0x48, so the two are printed as one step, `8/9`.  A new step 7b reads the
  calibration constants back and compares them, which is the other half of that limit.  FW-EEG-001 section 7.3 already
  says that where that table and this script differ, the script is what runs; the table still
  needs correcting and that document is not this station's to edit.

TWO THINGS HERE ARE PROPOSALS AND ARE MARKED AS SUCH
  * The configuration-zone template (`atecc608b_config.bin`, generated by
    `atecc608b_config.py`) is a SECURITY decision that nobody has reviewed, and the device
    opcode that writes it does not exist in the shipped firmware.  See
    ATECC608B_CONFIG_TEMPLATE.md, and in particular its reviewer checklist.
  * The calibration file schema (`calibration_schema.py`) fixes key names, units and ranges
    that no document had fixed.  Every key in it is a quantity a numbered test says it records.

WHERE THIS SCRIPT AND THE DOCUMENTS DISAGREE ABOUT NVS, THE FIRMWARE IS THE FACT
  FW-EEG-001 sections 2.5 and 7.3 and ASM-EEG-007 section 6.1 step 5 say the identity goes into
  namespace `eegcfg` in the `prov` partition and the constants into `eegcal` in `calib`.  The
  firmware does not do that.  `main.c` `handle_provision()` writes the keys
  `unit_serial`, `usb_ids`, `hw_rev` and `calib` through `drv_nvs_set_str/blob()`, and
  `drivers.c` lines 435-457 open namespace **"tiov" in the default `nvs` partition** for all of
  them; `prov` and `calib` are declared in partitions.csv, are never initialised and are never
  opened.  This script sends the opcodes, so it writes wherever the firmware puts them: the
  documents are wrong, not the code, and the correction belongs in those documents.  It is not
  cosmetic -- `drivers.c` calls `nvs_flash_erase()` unconditionally on
  ESP_ERR_NVS_NO_FREE_PAGES, so a full default NVS silently erases the unit serial and the
  calibration constants of an already-provisioned instrument.  See README_provisioning.md.

The device must already be running FW-EEG-001 and must enumerate as a CDC-ACM port.
Every command is a COBS-framed CMD frame on that port; the device answers with CMD_ACK.

Licence: MIT.
"""

def text_strokes(s, x, y, height=1.0, thickness=None, mirror=False, angle=0.0):
    """Return [(polyline, thickness)] for a string, baseline-left at (x, y).

    Y is up.  Mirror flips X about the string start (for bottom-side legend).
    """
    import math
    sc = height / H
    th = thickness or max(0.12, height * 0.15)
    out = []
    cx = 0.0
    ca, sa = math.cos(math.radians(angle)), math.sin(math.radians(angle))
    for ch in s.upper():
        g = _G.get(ch)
        if g is None:
            g = _G["-"]
        for poly in g:
            pts = []
            for px, py in poly:
                ux = (cx + px) * sc
                uy = py * sc
                if mirror:
                    ux = -ux
                pts.append((x + ux * ca - uy * sa, y + ux * sa + uy * ca))
            out.append((pts, th))
        cx += W + 1.0
    return out


def text_width(s, height=1.0):
    return len(s) * (W + 1.0) * height / H
